    /// <summary>The character a glyph name stands for (also from uniXXXX and uXXXX names), or null.</summary>
    public static int? Unicode(string name)
    {
        if (Unicodes.TryGetValue(name, out var u)) return u;
        var dot = name.IndexOf('.');
        if (dot > 0 && Unicodes.TryGetValue(name[..dot], out u)) return u; // a.sc, one.oldstyle
        if (name.StartsWith("uni", StringComparison.Ordinal) && name.Length >= 7 && int.TryParse(name.AsSpan(3, 4), System.Globalization.NumberStyles.HexNumber, null, out u)) return u;
        if (name.StartsWith('u') && name.Length is >= 5 and <= 7 && int.TryParse(name.AsSpan(1), System.Globalization.NumberStyles.HexNumber, null, out u)) return u;
        return null;
    }

